const img = (q: string, seed: number) =>
  `https://images.unsplash.com/photo-${q}?auto=format&fit=crop&w=640&q=70&sig=${seed}`;

const vehicleImageFolder = (category: VehicleCategory) => {
  const folders: Record<VehicleCategory, string> = {
    car: "cars",
    ev: "evs",
    bike: "bikes",
    scooter: "scooters",
  };

  return folders[category];
};

export const vehicleImagePath = (vehicle: Pick<Vehicle, "category" | "slug">) =>
  `/images/vehicles/${vehicleImageFolder(vehicle.category)}/${vehicle.slug}.webp`;

