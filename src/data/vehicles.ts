const getCategoryImages = (
  category: VehicleCategory,
  bodyType: string,
  isElectric: boolean,
  brand: string,
  name: string,
  seed: number,
): string[] => {
  let pool: string[] = [];

  // Categorize vehicle into precise, highly specific pools matching brand and style
  if (category === "car" || category === "ev") {
    if (brand === "Mahindra" && (name.includes("Thar") || name.includes("Scorpio"))) {
      pool = POOLS.suv_rugged;
    } else if (brand === "Toyota" && name.includes("Fortuner")) {
      pool = POOLS.suv_rugged;
    } else if (bodyType === "SUV") {
      pool = POOLS.suv_crossover;
    } else if (bodyType === "Hatchback") {
      pool = POOLS.hatchback;
    } else if (bodyType === "Sedan") {
      pool = POOLS.sedan;
    } else {
      pool = POOLS.suv_crossover; // Fallback
    }
  } else if (category === "bike") {
    if (bodyType === "Adventure") {
      pool = POOLS.bike_adventure;
    } else if (bodyType === "Cruiser" || brand === "Royal Enfield" || brand === "Harley-Davidson") {
      pool = POOLS.bike_cruiser;
    } else {
      pool = POOLS.bike_sport;
    }
  } else {
    // Scooters
    if (brand === "Vespa" || brand === "Honda" || brand === "Suzuki" || brand === "TVS") {
      if (isElectric) {
        pool = POOLS.scooter_modern;
      } else {
        pool = POOLS.scooter_retro;
      }
    } else {
      pool = POOLS.scooter_modern;
    }
  }

  // Retrieve 5 unique images from the pool deterministically sharded by seed
  // This ensures Maruti Swift and Hyundai i20 show completely unique images!
  const images: string[] = [];
  const poolSize = pool.length;
  for (let i = 0; i < 5; i++) {
    const index = (seed + i * 3) % poolSize;
    images.push(pool[index]);
  }

  return images.map((id, index) => img(id, seed + index * 10));
};

